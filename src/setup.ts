import { input, password, confirm } from '@inquirer/prompts';
import { open, lstat, rename, unlink } from 'node:fs/promises';
import { resolve, dirname, join } from 'node:path';
import { randomUUID } from 'node:crypto';
import { loadConfig, type Config } from './config.js';
import { BrightspaceClient } from './client.js';
import { setupGuide } from './setup-guide.js';

export function normalizeHost(value: string): string {
  const url = new URL(value.trim());
  if (url.protocol !== 'https:' || url.username || url.password) throw new Error('Enter an HTTPS Brightspace URL without embedded credentials.');
  return url.origin;
}

export function serializeConfig(config: Config): string {
  // JSON quoting is compatible with Node's dotenv parser for these single-line values.
  // Reject quote/backslash/newline tokens rather than risk dotenv interpretation changes.
  if (/[\r\n'"`\\]/.test(config.accessToken)) throw new Error('Access token contains unsupported characters. Copy only the access_token value.');
  return '# Generated by brightspace-mcp setup. Keep this file private.\n' + Object.entries({
    BRIGHTSPACE_BASE_URL: config.baseUrl,
    BRIGHTSPACE_ACCESS_TOKEN: config.accessToken,
    BRIGHTSPACE_LP_VERSION: config.lpVersion,
    BRIGHTSPACE_LE_VERSION: config.leVersion,
  }).map(([key, value]) => `${key}=${JSON.stringify(value)}`).join('\n') + '\n';
}

export async function saveConfig(path: string, config: Config, overwrite = false) {
  const contents = serializeConfig(config);
  if (!overwrite) {
    const file = await open(path, 'wx', 0o600);
    try { await file.writeFile(contents); } finally { await file.close(); }
    return;
  }
  // Never follow a symlink or truncate an existing file before the replacement is complete.
  const existing = await lstat(path).catch((error: NodeJS.ErrnoException) => {
    if (error.code === 'ENOENT') return undefined;
    throw error;
  });
  if (existing && !existing.isFile()) throw new Error('Refusing to replace a non-regular configuration file.');
  const temporary = join(dirname(path), `.brightspace-setup-${randomUUID()}.tmp`);
  try {
    const file = await open(temporary, 'wx', 0o600);
    try { await file.writeFile(contents); } finally { await file.close(); }
    await rename(temporary, path);
  } finally { await unlink(temporary).catch(() => {}); }
}

export async function runSetup() {
  if (!process.stdin.isTTY || !process.stdout.isTTY) throw new Error('Setup needs an interactive terminal. Run npm run setup in your terminal, not through MCP stdio.');
  console.log('\nBrightspace MCP setup\n');
  for (const instruction of setupGuide.instructions.slice(1, 6)) console.log(`${instruction}\n`);
  console.log(`Required OAuth scopes: ${setupGuide.scopes.join(' ')}\nOfficial guide: ${setupGuide.oauth.documentation}\n`);
  const host = await input({ message: 'Brightspace URL:', validate: value => {
    try { normalizeHost(value); return true; } catch { return 'Enter your school’s HTTPS Brightspace URL.'; }
  } });
  const token = await password({ message: 'Your OAuth access token (hidden):', mask: '*', validate: value =>
    value.trim() && !/[\r\n'"`\\]/.test(value) ? true : 'Paste only the single-line access_token value.' });
  const version = (value: string) => /^\d+\.\d+$/.test(value) || 'Use a version such as 1.49.';
  const lp = await input({ message: 'LP API version:', default: '1.49', validate: version });
  const le = await input({ message: 'LE API version:', default: '1.82', validate: version });
  const config = loadConfig({ BRIGHTSPACE_BASE_URL: normalizeHost(host), BRIGHTSPACE_ACCESS_TOKEN: token,
    BRIGHTSPACE_LP_VERSION: lp, BRIGHTSPACE_LE_VERSION: le });
  if (await confirm({ message: `Check enrollment access at ${config.baseUrl}?`, default: true })) {
    try {
      const courses = await new BrightspaceClient(config).getCourses();
      console.log(`Connection succeeded (${courses.length} course offerings). Other tool permissions have not been checked.`);
    } catch (error) {
      console.log(error instanceof Error ? error.message : 'Connection check failed.');
      if (!await confirm({ message: 'Save anyway so you can fix the configuration later?', default: false })) return;
    }
  }
  const path = resolve('.env');
  const existing = await lstat(path).catch((error: NodeJS.ErrnoException) => {
    if (error.code === 'ENOENT') return undefined;
    throw error;
  });
  if (existing && !await confirm({ message: `Replace ${path}? This replaces the entire file, including any other settings.`, default: false })) return;
  await saveConfig(path, config, !!existing);
  console.log(`\nSaved ${path} with owner-only permissions.\nStart with: node --env-file=${JSON.stringify(path)} dist/index.js\nRestart your MCP client after updating the token. See README.md for client configuration.`);
}
